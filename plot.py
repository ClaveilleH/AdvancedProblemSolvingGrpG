import matplotlib.pyplot as plt
import pandas as pd

path= "convergence1.csv"

df = pd.read_csv(path, header=None)  
for i, ligne in df.iterrows():
    plt.plot(ligne.values, label=f"Ligne {i}")  # x = indice automatiquement

plt.xlabel("Indice")
plt.ylabel("Valeur")
plt.legend()
plt.show()


